import argparse
import os
import pickle
import sys
from pathlib import Path
import pandas as pd
import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from reproducibility import split_subjects, split_validation_subjects

parser = argparse.ArgumentParser(description='Create reproducible patient-level dataset splits.')
parser.add_argument('--seed', type=int, default=None, help='Seed used for the patient-level split.')
args = parser.parse_args()
config_path = Path(__file__).resolve().parents[1] / 'config' / 'base.yaml'
with config_path.open('r', encoding='utf-8') as config_file:
    config = yaml.safe_load(config_file)
args.seed = config.get('seed', 2026) if args.seed is None else args.seed
if args.seed < 0:
    parser.error('--seed must be a non-negative integer')

# Target variables are loaded from var.pkl, generated by step_2.py.
var, target_var = pickle.load(open('data/var.pkl', 'rb'))
samples = []
info = []

for file in sorted(os.listdir('data/first')):
    sr, ir = pickle.load(open('data/first/' + file, 'rb'))
    samples += sr
    info += ir
info = pd.DataFrame(info, columns = ['ts_ind', 'sub_id', 'x_len', 'y_len'])

# Patient-wise split. Keep split membership in a sidecar for audit/reuse.
train_sub, valid_sub, test_sub = split_subjects(info['sub_id'].to_numpy(), seed=args.seed)
val_model_sub, calibration_sub = split_validation_subjects(valid_sub, seed=args.seed)

# Fit normalization and the independent evaluation reference on training patients only.
rec = [[] for _ in range(len(var))]

for sub_id in train_sub:
    index = np.array(info.loc[info.sub_id == sub_id].index)
    for i in index:
        stay = samples[i]
        for j in range(info.iloc[i]['x_len']):
            feature_id = stay[0][j]
            value = stay[2][j]
            rec[feature_id].append(value)

mean = np.full(len(var), np.nan)
std = np.full(len(var), np.nan)
for i in range(len(var)):
    if len(rec[i]) > 0:
        mean[i] = np.array(rec[i]).mean()
        std[i] = np.array(rec[i]).std()

reference_scale_path = Path('data/evaluation_reference_scale.pkl')
if reference_scale_path.is_file():
    with reference_scale_path.open('rb') as reference_file:
        reference = pickle.load(reference_file)
    if reference.get('variable_names') != list(var) or not np.array_equal(reference.get('target_ids'), target_var):
        raise ValueError('Frozen evaluation scales do not match the current target layout. Archive the old reference explicitly before creating a new benchmark scale; it will not be overwritten silently.')
    frozen_scales = np.asarray(reference.get('scales'), dtype=float)
    if frozen_scales.shape != (len(var),) or not np.isfinite(frozen_scales[target_var]).all() or np.any(frozen_scales[target_var] <= 0):
        raise ValueError('Frozen evaluation scales are missing or invalid for target variables.')
else:
    reference_scales = np.ones(len(var), dtype=float)
    for feature_id in target_var:
        observations = np.asarray(rec[int(feature_id)], dtype=float)
        if not len(observations) or not np.isfinite(observations).all():
            raise ValueError('Cannot create a finite frozen evaluation scale for target {}'.format(var[int(feature_id)]))
        scale = float(observations.std())
        if not np.isfinite(scale) or scale <= 0:
            raise ValueError('Frozen evaluation scale must be positive for target {}'.format(var[int(feature_id)]))
        reference_scales[int(feature_id)] = scale
    reference = {
        'version': 1,
        'variable_names': list(var),
        'target_ids': np.asarray(target_var, dtype=int),
        'scales': reference_scales,
        'source': 'raw observed context values from training patients',
        'seed': int(args.seed),
    }
    with reference_scale_path.open('wb') as reference_file:
        pickle.dump(reference, reference_file)

sub_sets = [train_sub, val_model_sub, calibration_sub, test_sub]
data_sets = [[], [], [], []]
info_sets = [[], [], [], []]
for si in range(len(sub_sets)):
    for sub_id in sub_sets[si]:
        index = np.array(info.loc[info.sub_id == sub_id].index)
        for i in index:
            stay = samples[i]
            for j in range(len(samples[i][0])):
                if np.isnan(mean[stay[0][j]]):
                    stay[2][j] = 0
                else:
                    s = 1 if std[stay[0][j]] == 0 else std[stay[0][j]]
                    stay[2][j] = (stay[2][j] - mean[stay[0][j]]) / s
            data_sets[si].append(stay)
            info_sets[si].append(info.iloc[i])

pickle.dump([mean, std], open('data/mean_std.pkl','wb'))
pickle.dump([
    data_sets[0], pd.DataFrame(info_sets[0]),
    data_sets[1], pd.DataFrame(info_sets[1]),
    data_sets[2], pd.DataFrame(info_sets[2]),
    data_sets[3], pd.DataFrame(info_sets[3]),
], open('data/dataset.pkl','wb'))
with open('data/splits.pkl', 'wb') as split_file:
    pickle.dump({
        'seed': args.seed,
        'train_subjects': train_sub,
        'valid_subjects': val_model_sub,
        'model_validation_subjects': val_model_sub,
        'calibration_subjects': calibration_sub,
        'legacy_valid_subjects': valid_sub,
        'test_subjects': test_sub,
    }, split_file)
